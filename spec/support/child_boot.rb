# frozen_string_literal: true

require "digest"
require "fileutils"

# Children inherit the worker's ENV, so rewriting it once gives every spawned Ruby static load
# paths instead of a `bundler/setup` re-resolve, and a heap that does not collect 17 times
# while `require "lain"` fills it. Specs only: an installed gem has no Gemfile.lock to key on.
# Children that clear RUBYOPT (Lain::Exec::FRAMEWORK_ENV) keep their own bundle, and `exe/lain`
# requires `bundler/setup` itself, so it gets the heap sizing only.
module ChildBoot
  # Just under the object counts at the end of `require "lain"`; sizing for zero collections
  # costs 30MB per child and buys little.
  GC_SETTINGS = {
    "RUBY_GC_HEAP_0_INIT_SLOTS" => "350000", "RUBY_GC_HEAP_1_INIT_SLOTS" => "70000",
    "RUBY_GC_HEAP_2_INIT_SLOTS" => "50000", "RUBY_GC_HEAP_3_INIT_SLOTS" => "4000",
    "RUBY_GC_HEAP_4_INIT_SLOTS" => "3000", "RUBY_GC_MALLOC_LIMIT" => "64000000",
    "RUBY_GC_OLDMALLOC_LIMIT" => "128000000"
  }.freeze

  # `bundle exec` writes the absolute path of its setup file, not the bare feature name.
  BUNDLER_SETUP = %r{-r\S*bundler/setup}

  module_function

  # @param env [#[], #[]=, #delete] the environment children inherit
  # @return [String, nil] the generated load-path file now in RUBYOPT, when one was swapped in
  def install(env: ENV)
    return if env["LAIN_NO_CHILD_BOOT"] == "1"

    GC_SETTINGS.each { |name, value| env[name] ||= value }
    swap_bundler_setup(env) if env["RUBYOPT"].to_s.match?(BUNDLER_SETUP)
  end

  def cache_dir = File.join(File.expand_path("../..", __dir__), "tmp", "cache", "child_boot")

  # BUNDLER_SETUP goes with the `-r`: while it is set, rubygems loads all of bundler at boot to honour it.
  def swap_bundler_setup(env)
    file = load_path_file
    env["RUBYOPT"] = env["RUBYOPT"].gsub(BUNDLER_SETUP, "-r#{file}")
    env.delete("BUNDLER_SETUP")
    file
  end

  # Named by its own content, so any change in what bundler resolved (lock, groups, local
  # overrides, ruby, gem home) is a new file and a stale one is never read.
  def load_path_file
    text = script
    path = File.join(cache_dir, "#{Digest::SHA256.hexdigest(text)[0, 16]}.rb")
    write_atomically(path, text) unless File.exist?(path)
    path
  end

  # Gem::Specification.all is narrowed to the locked specs, bundler and the default gems so
  # `gem` for anything else raises as under bundler/setup; the exceptions are what binstubs
  # (`bundle`, `rake`) resolve their own dependencies from.
  def script
    locked = Bundler.load.specs
    specs = locked.reject { |spec| spec.name == "bundler" }
    files = (locked.map(&:loaded_from) + [Gem::Specification.find_by_name("bundler").loaded_from]).uniq
    <<~RUBY
      # Generated by spec/support/child_boot.rb: the locked load paths and specs, without bundler/setup.
      Gem.discover_gems_on_require = false
      defaults = Gem::Specification.select(&:default_gem?)
      Gem::Specification.all = #{files.inspect}.filter_map { |file| Gem::Specification.load(file) } | defaults
      #{specs.flat_map(&:full_require_paths).uniq.reverse.map { |path| "$:.unshift #{path.dump}" }.join("\n")}
    RUBY
  end

  # Workers race to one name; rename is atomic, so nobody reads a half-written file.
  def write_atomically(path, text)
    FileUtils.mkdir_p(File.dirname(path))
    scratch = "#{path}.#{Process.pid}"
    File.write(scratch, text)
    File.rename(scratch, path)
  end
end

ChildBoot.install
