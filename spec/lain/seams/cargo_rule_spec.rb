# frozen_string_literal: true

require "digest"
require "fileutils"
require "tmpdir"

# A cargo build the composed_term rule approves, run by the production bash tool through the session's own
# board, guard and sandbox. The crate depends on 1 crate this box has cached, and its own config holds cargo
# offline, so no run here can reach the network whichever profile it gets.
RSpec.describe "A cargo build the composed_term rule approves", :seam do
  # Short: a long path in what cargo prints reads as a high-entropy token, which withholds the output.
  around do |example|
    @base = File.realpath(Dir.mktmpdir("cr", ENV.fetch("TMPDIR", Dir.tmpdir)))
    example.run
  ensure
    FileUtils.rm_rf(@base) if @base
  end

  let(:registry) { File.join(Dir.home, ".cargo/registry") }
  let(:cached) do
    Dir.glob(File.join(registry, "cache/*/itoa-*.crate")).find do |path|
      File.directory?(File.join(registry, "src", File.basename(File.dirname(path)), File.basename(path, ".crate")))
    end
  end
  let(:root) { File.join(@base, "crate") }
  let(:fence) { Lain::Confine::Bwrap.fence_binary }
  let(:confine) { :workspace }
  let(:journal) { RecordingChannel.new }
  let(:paths) do
    Lain::Paths.new(env: { "HOME" => Dir.home, "XDG_STATE_HOME" => File.join(@base, "state") })
  end
  let(:project) { Lain::Project.new(root:, cwd: root, kind: :project, detected_by: :flag) }
  let(:session) { Lain::Session.new(worker_env: Lain::WorkerEnv.default.with(cwd: root)) }
  let(:resolver) do
    Lain::Shell::Executable::Resolver.new(root:, fresh: Lain::Shell::Executable::Resolver::NeverFresh)
  end
  let(:chronicle) { Lain::CLI::Chronicle::Null.new }
  let(:arms) { Lain::CLI::Arms::OFF.with(confine:) }
  let(:switchboard) do
    Lain::CLI::Wiring::BoardBuild.for(
      human: Lain::CLI::Human.new(kind: :terminal),
      chronicle:, options: { approval: :auto }, judge: Lain::CLI::Switchboard::DEFERRING, model: "test-model",
      project:, paths:, toolset: Lain::Toolset.new([Lain::Tools::Bash.new]), arms:,
      verdict: Lain::CLI::Wiring::BoardBuild.shell_verdict(project:, paths: Lain::Paths.new), resolver:,
      worker_env: session.worker_env
    ).bind_session(session)
  end
  let(:parent) { -> { Lain::Dag::Factory.timeline(store: Lain::Dag::Factory.store) } }
  let(:toolset_build) do
    backend = Lain::CLI::Backend.new({ provider: "ollama", model: nil, max_tokens: 64 }, root:)
    Lain::CLI::Wiring::ToolsetBuild.new(
      backend:, provider: Lain::Provider::Mock.new, chronicle:, options: {}, journal:, library: backend.library,
      supervisor: Lain::Supervisor.new(journal:), parent:, epic: SpecNulls.unmounted_epic, root:,
      switchboard: -> { switchboard }, askers: SpecNulls::UnwiredAskers.build, paths:,
      config: SpecNulls.unloaded_project.fetch(:config), exec: Lain::Exec::Local.new, arms:, resolver:
    )
  end
  let(:bash) do
    ask_human = Lain::Tools::AskHuman.new(parent: -> { CoreGraph.timeline })
    toolset_build.build(Lain::Memory::Recorder.new, ask_human:).fetch("bash")
  end

  before do
    skip("bwrap or strace is not installed") unless %w[/usr/bin/bwrap /usr/bin/strace].all? { File.executable?(_1) }
    skip("lain-fence is not built at #{fence} -- run `bundle exec rake compile`") unless File.executable?(fence)
    skip("no cargo on PATH") unless ENV.fetch("PATH", "").split(":").any? { File.executable?(File.join(_1, "cargo")) }
    skip("no itoa crate cached and unpacked in #{registry}") unless cached
    seed_crate
  end

  def seed_crate
    version = File.basename(cached, ".crate").delete_prefix("itoa-")
    write("Cargo.toml", "[package]\nname = \"c1\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n" \
                        "[dependencies]\nitoa = \"=#{version}\"\n")
    write("Cargo.lock", lockfile(version))
    # A seam must never reach the network, whatever profile runs it.
    write(".cargo/config.toml", "[net]\noffline = true\n")
    write("src/lib.rs", "pub fn digits(n: u32) -> String { itoa::Buffer::new().format(n).to_owned() }\n")
  end

  def lockfile(version)
    <<~LOCK
      # This file is automatically @generated by Cargo.
      # It is not intended for manual editing.
      version = 4

      [[package]]
      name = "c1"
      version = "0.1.0"
      dependencies = [
       "itoa",
      ]

      [[package]]
      name = "itoa"
      version = "#{version}"
      source = "registry+https://github.com/rust-lang/crates.io-index"
      checksum = "#{Digest::SHA256.file(cached).hexdigest}"
    LOCK
  end

  def write(name, body)
    File.join(root, name).tap { FileUtils.mkdir_p(File.dirname(_1)) }.then { File.write(_1, body) }
  end

  def run(command)
    layers = Lain::CLI::ToolGuard.stack(chronicle, switchboard).to_a
    Sync do |task|
      task.with_timeout(170) do
        dispatch_call("bash", { "command" => command }, toolset: Lain::Toolset.new([bash]), layers:, context: session)
      end
    end
  end

  def profiles = journal.events.grep(Lain::Telemetry::Sandbox).map(&:profile)

  # Quiet, since the TMPDIR is the runner's and may still be long enough to withhold the path cargo prints.
  it "runs a locked cargo check under the workspace profile, writing target/ from the cached registry" do
    result = run("cargo check --locked --quiet")

    expect(result.content).to start_with("exit status: 0"), result.content
    expect(profiles).to eq(%i[workspace])
    expect(Dir.glob(File.join(root, "target/debug/**/*itoa*"))).not_to be_empty
  end

  it "runs the usual cargo test pipeline under the workspace profile" do
    result = run("cargo test --locked 2>&1 | tail -5")

    expect(result.content).to start_with("exit status: 0").and(include("test result: ok")), result.content
    expect(profiles).to eq(%i[workspace])
  end

  it "keeps a version probe, fmt --check and a plain read on the reader profile" do
    ["cargo --version", "cargo fmt --check", "cat Cargo.toml"].each { run(_1) }

    expect(profiles).to eq(%i[reader reader reader])
  end

  it "runs a version probe on the string arm under the reader profile, with the program its stage names" do
    result = run("cargo --version 2>&1 | head -1")

    expect(result.content).to start_with("exit status: 0").and(include("cargo 1.")), result.content
    expect(profiles).to eq(%i[reader])
  end

  context "when the session was launched with --confine reader" do
    let(:confine) { :reader }

    it "keeps a locked cargo check on the reader profile" do
      run("cargo check --locked")

      expect(profiles).to eq(%i[reader])
    end
  end
end
