# frozen_string_literal: true

RSpec.describe Lain::Notices do
  let(:bin) { Dir.mktmpdir("lain-notices-bin") }
  let(:notes) { StringIO.new }

  after { FileUtils.remove_entry(bin) }

  def write_binstub(dir)
    File.write(File.join(dir, "notify-feed"), "#!/bin/sh\n#\n# This file was generated by RubyGems.\n#\nexit 1\n",
               perm: 0o755)
  end

  def install(name)
    path = File.join(bin, name)
    File.write(path, "#!/bin/sh\nexit 0\n")
    File.chmod(0o755, path)
    path
  end

  describe ".for" do
    it "is a Null, spawning nothing, when notify-feed is not on PATH" do
      notices = described_class.for(env: { "PATH" => bin }, notes:)

      expect(notices).to be_a(Lain::Notices::Null)
      expect(notices.call("lain", "title", "body")).to be(false)
    end

    it "is a Feed over the notify-feed found on PATH" do
      install("notify-feed")

      expect(described_class.for(env: { "PATH" => bin }, notes:)).to be_a(Lain::Notices::Feed)
    end

    it "skips a RubyGems binstub named notify-feed for a later one on PATH" do
      stubs = Dir.mktmpdir("lain-notices-gem")
      write_binstub(stubs)
      ran = File.join(bin, "ran")
      File.write(File.join(bin, "notify-feed"), "#!/bin/sh\ntouch #{ran}\n", perm: 0o755)

      described_class.for(env: { "PATH" => [stubs, bin].join(File::PATH_SEPARATOR) }, notes:).call("lain", "t", "b")

      expect(notes.string).to eq("")
      expect(File).to exist(ran)
    ensure
      FileUtils.remove_entry(stubs)
    end

    it "is a Null when the only notify-feed is a RubyGems binstub" do
      write_binstub(bin)

      expect(described_class.for(env: { "PATH" => bin }, notes:)).to be_a(Lain::Notices::Null)
    end

    it "finds a real notify-feed in the gem bin dir, which a distro ruby keeps in /usr/bin" do
      install("notify-feed")
      allow(Gem).to receive_messages(default_bindir: bin, bindir: bin)

      expect(described_class.for(env: { "PATH" => bin }, notes:)).to be_a(Lain::Notices::Feed)
    end

    it "names a failing feed, by its path, on the notes sink" do
      path = File.join(bin, "notify-feed")
      File.write(path, "#!/bin/sh\nexit 1\n")
      File.chmod(0o755, path)

      described_class.for(env: { "PATH" => bin }, notes:).call("lain", "t", "b")

      expect(notes.string).to eq("#{path} exited 1\n")
    end

    it "does not find a notify-feed in the cwd through an empty PATH entry" do
      install("notify-feed")

      Dir.chdir(bin) { expect(described_class.for(env: { "PATH" => "::" }, notes:)).to be_a(Lain::Notices::Null) }
    end

    it "is a Null when PATH is unset" do
      expect(described_class.for(env: {}, notes:)).to be_a(Lain::Notices::Null)
    end
  end
end
