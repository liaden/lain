# frozen_string_literal: true

module Lain
  # Notes for a human who is not at the terminal, handed to the `notify-feed` program.
  module Notices
    PROGRAM = "notify-feed"

    # The PATH search's filesystem, blind to a RubyGems binstub: one is a Ruby wrapper that can
    # outlive its gem. Judged by content, not directory, because a distro ruby's gem bin dir is
    # /usr/bin, where a real notify-feed may sit.
    module Candidates
      MARKER = "This file was generated by RubyGems."
      HEAD = 512

      # @param path [String]
      # @return [Boolean] a regular file that is not a RubyGems binstub
      def self.file?(path) = File.file?(path) && !binstub?(path)

      # @param path [String]
      # @return [Boolean]
      def self.executable?(path) = File.executable?(path)

      # @param path [String]
      # @return [Boolean] whether the file's head carries the stub generator's line
      def self.binstub?(path)
        File.binread(path, HEAD).to_s.include?(MARKER)
      rescue SystemCallError
        false
      end
    end

    # @param env [#[]] the process environment, searched for {PROGRAM} on PATH
    # @param notes [#puts] where a failing feed is named
    # @return [Feed, Null]
    def self.for(env:, notes:)
      found = Shell::Path.find(PROGRAM, path: env["PATH"], filesystem: Candidates)
      found ? Feed.new(program: found, notes:, env:) : Null.new
    end
  end
end
