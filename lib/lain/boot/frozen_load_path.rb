# frozen_string_literal: true

require "digest"
require "fileutils"

module Lain
  module Boot
    # What `bundler/setup` resolved for a checkout, kept as a Ruby file that replays it: the load
    # path, the gem specs and the ENV it exported. Plain Ruby with no gem dependency, because
    # `exe/lain` loads it by absolute path before any gem is activated.
    #
    # The key hashes file stats rather than contents, so a hit costs a few syscalls. A changed key is a new file
    # rather than a rewrite, so worktrees and environments that differ do not evict each other.
    module FrozenLoadPath
      # Bundler reads these, and the ENV it exports is built from them, so a recorded export is only
      # replayed into the environment it was recorded from.
      KEYED_ENV = /\A(?:BUNDLE_|BUNDLER_|GEM_|RUBY|PATH\z|MANPATH\z|HOME\z|RB_USER_INSTALL\z)/

      class << self
        # @param gemfile [String] the Gemfile `bundler/setup` would resolve
        # @param cache_dir [String] where the replay files live
        # @return [Boolean] true when the cached path was loaded, false when Bundler ran
        def setup(gemfile:, cache_dir:)
          cache = File.join(cache_dir, "#{key(gemfile)}.rb")
          # A Bundler that already ran owns the load path; replaying over it would fight it.
          return true if !defined?(::Bundler) && replay(cache)

          record(cache)
          false
        end

        # Gem::Specification.all is narrowed to the locked specs, bundler and the default gems so
        # `gem` for anything else raises as under bundler/setup; the exceptions are what binstubs
        # (`bundle`, `rake`) resolve their own dependencies from. The defaults come from their stubs,
        # because asking the full specification list for them loads every installed gemspec.
        #
        # @param specs [Array<Gem::Specification>] the locked specs, bundler's among them
        # @return [String] Ruby that sets the load path and gem specs those specs need
        def script(specs = ::Bundler.load.specs)
          <<~RUBY
            Gem.discover_gems_on_require = false
            defaults = Gem::Specification.default_stubs.map(&:to_spec)
            Gem::Specification.all = #{spec_files(specs).inspect}.filter_map { |file| Gem::Specification.load(file) } | defaults
            #{require_paths(specs).reverse.map { |path| "$:.unshift #{path.dump}" }.join("\n")}
          RUBY
        end

        # Launches race to one name; the rename is atomic and follows an fsync, so nobody reads a
        # half-written file, even after a crash. A cache that cannot be written must never stop a launch.
        #
        # @param path [String] where the file lands
        # @param text [String] its contents
        # @return [Boolean] whether the file was written
        def write_atomically(path, text)
          FileUtils.mkdir_p(File.dirname(path))
          scratch = "#{path}.#{Process.pid}"
          File.open(scratch, "w") do |file|
            file.write(text)
            file.fsync
          end
          File.rename(scratch, path)
          true
        rescue SystemCallError
          FileUtils.rm_f(scratch) if scratch
          false
        end

        private

        # A replay file naming a path gone since it was written raises LoadError before it changes anything.
        # An empty or cut-short one is what a crash mid-write leaves, and must not stop a launch either.
        def replay(cache)
          return false unless File.size?(cache)

          load cache
          true
        rescue ScriptError
          false
        end

        def record(cache)
          before = ENV.to_h
          return unless require "bundler/setup"

          write_atomically(cache, replay_script(before, ENV.to_h))
        end

        def replay_script(before, after)
          specs = ::Bundler.load.specs
          needed = (spec_files(specs) + require_paths(specs)).select { File.exist?(_1) }
          <<~RUBY
            # Generated by Lain::Boot::FrozenLoadPath: what bundler/setup resolved, replayed without it.
            missing = #{needed.inspect}.reject { |path| File.exist?(path) }
            raise LoadError, "the frozen load path names missing files: \#{missing.join(", ")}" unless missing.empty?
            ENV.update(#{after.reject { |name, value| before[name] == value }.inspect})
            Gem.clear_paths
            #{script(specs)}
          RUBY
        end

        def key(gemfile)
          root = File.dirname(gemfile)
          gemspecs = Dir.glob("*.gemspec", base: root).map { File.join(root, _1) }
          files = [gemfile, "#{gemfile}.lock", *gemspecs, app_config(root),
                   user_config, File.join(Gem.dir, "specifications"), RbConfig.ruby]
          inputs = [RUBY_VERSION, *files.map { stamp(_1) }, *ENV.select { |name, _| name.match?(KEYED_ENV) }.sort]
          Digest::SHA256.hexdigest(inputs.join("\0"))[0, 32]
        end

        def stamp(path)
          return "#{path} absent" unless File.exist?(path)

          stat = File.stat(path)
          "#{path} #{stat.mtime.to_i}.#{stat.mtime.nsec} #{stat.size}"
        end

        def app_config(root) = File.join(ENV.fetch("BUNDLE_APP_CONFIG") { File.join(root, ".bundle") }, "config")

        def user_config
          ENV.fetch("BUNDLE_USER_CONFIG") do
            File.join(ENV.fetch("BUNDLE_USER_HOME") { File.join(ENV.fetch("HOME", ""), ".bundle") }, "config")
          end
        end

        def spec_files(specs)
          bundler = Gem::Specification.find_by_name("bundler").loaded_from
          (specs.map(&:loaded_from) + [bundler]).uniq
        end

        def require_paths(specs) = specs.reject { _1.name == "bundler" }.flat_map(&:full_require_paths).uniq
      end
    end
  end
end
